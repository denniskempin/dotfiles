//! Every real binding as text. `tests/snapshot.txt` is the oracle: a port that
//! drifts shows up as a diff of the keys it changes.

use crate::keys::{probed_keys, KeyMap};
use crate::model::{Compiled, Flags, Layer};
use crate::world::{World, WorldOpts};
use std::sync::Arc;

const UNLISTED: &str = "com.example.Unlisted";

pub fn generate(grammar: Arc<Compiled>) -> (String, Vec<String>) {
    let keys = probed_keys(&KeyMap::us());
    let mut apps: Vec<String> = grammar.apps.keys().cloned().collect();
    apps.sort();
    apps.push(UNLISTED.to_string());

    let mut lines = vec![
        "# Generated by cargo test -p keyagent --test scenarios. Each line is a key and what"
            .to_string(),
        "# it did: posted keys, processes started, menu items tried, and the overlay".to_string(),
        "# left showing. Keys that did nothing are left out.".to_string(),
    ];
    let mut problems = Vec::new();
    section(
        &mut lines,
        "System layer, Caps Lock held",
        &grammar,
        Layer::Os,
        UNLISTED,
        None,
        &[false, true],
        &keys,
        &mut problems,
    );
    for (key, title) in grammar.chord_starters(Layer::Os) {
        section(
            &mut lines,
            &format!("System layer, {key} then the key ({title})"),
            &grammar,
            Layer::Os,
            UNLISTED,
            Some(key.as_str()),
            &[false],
            &keys,
            &mut problems,
        );
    }
    for app in &apps {
        section(
            &mut lines,
            &format!("App layer, Fn held, in {app}"),
            &grammar,
            Layer::App,
            app,
            None,
            &[false, true],
            &keys,
            &mut problems,
        );
        for (key, title) in grammar.chord_starters(Layer::App) {
            section(
                &mut lines,
                &format!("App layer, {key} then the key ({title}), in {app}"),
                &grammar,
                Layer::App,
                app,
                Some(key.as_str()),
                &[false],
                &keys,
                &mut problems,
            );
        }
    }
    (format!("{}\n", lines.join("\n")), problems)
}

fn section(
    lines: &mut Vec<String>,
    header: &str,
    grammar: &Arc<Compiled>,
    layer: Layer,
    front: &str,
    starter: Option<&str>,
    shifts: &[bool],
    keys: &[String],
    problems: &mut Vec<String>,
) {
    lines.push(String::new());
    lines.push(format!("# {header}"));
    let mut any = false;
    for key in keys {
        for shift in shifts {
            let parts = probe(grammar, layer, front, starter, key, *shift, problems);
            if !parts.is_empty() {
                any = true;
                let name = if *shift {
                    format!("shift+{key}")
                } else {
                    key.clone()
                };
                lines.push(format!("{name:<14} {}", parts.join(" ; ")));
            }
        }
    }
    if !any {
        lines.push("(nothing)".to_string());
    }
}

fn probe(
    grammar: &Arc<Compiled>,
    layer: Layer,
    front: &str,
    starter: Option<&str>,
    key: &str,
    shift: bool,
    problems: &mut Vec<String>,
) -> Vec<String> {
    let mut world = World::new(
        Arc::clone(grammar),
        WorldOpts {
            front: Some(front.to_string()),
            ..WorldOpts::default()
        },
    );
    let title = world.layer_title(layer);
    let hold = match layer {
        Layer::Os => "f18",
        Layer::App => "f19",
    };
    world.down(hold, Flags::empty());
    if let Some(starter) = starter {
        world.press(starter, Flags::empty());
    }
    let mut flags = Flags::empty();
    flags.shift = shift;
    world.press(key, flags);
    world.advance(2.0);
    let overlay = world.overlay();
    let note = (overlay.visible && overlay.title != title).then_some(overlay.title);
    world.up(hold, Flags::empty());
    world.settle();
    let mut parts = world.effects();
    if let Some(note) = note {
        parts.push(format!("overlay {note:?}"));
    }
    for problem in world.problems() {
        problems.push(problem.clone());
    }
    for warning in world.warnings() {
        problems.push(format!("warning: {warning}"));
    }
    parts
}
