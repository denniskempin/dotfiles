-- Every binding as text. Each key, with and without Shift, is pressed in a
-- fresh world for every layer, app, and chord, and the keys that do anything
-- are listed with what they did. run.lua compares the result with
-- snapshot.txt, so a change to the config shows up as a diff of the keys it
-- changes.

local world = require("world")

local UNLISTED = "com.example.Unlisted"

local NOT_PROBED = {
  f18 = true, f19 = true, fn = true, capslock = true,
  cmd = true, alt = true, ctrl = true, shift = true,
  rightcmd = true, rightalt = true, rightctrl = true, rightshift = true,
}

local ARROWS = { left = 1, down = 2, up = 3, right = 4 }

local function sortKey(name)
  if ARROWS[name] then return 1, ARROWS[name] end
  if name:match("^%l$") then return 2, name end
  if name:match("^%d$") then return 3, name end
  if #name == 1 then return 4, name end
  if name:match("^f%d+$") then return 6, tonumber(name:sub(2)) end
  if name:match("^pad") then return 7, name end
  return 5, name
end

local KEYS = {}
for _, name in pairs(world.CODES) do
  if not NOT_PROBED[name] then KEYS[#KEYS + 1] = name end
end
table.sort(KEYS, function(a, b)
  local ga, ka = sortKey(a)
  local gb, kb = sortKey(b)
  if ga ~= gb then return ga < gb end
  if type(ka) ~= type(kb) then return tostring(ka) < tostring(kb) end
  return ka < kb
end)

local HOLD = { os = "f18", app = "f19" }

local function probe(layer, front, starter, key, shift, problems)
  local w = world.new({ front = front })
  local title = w.modules.bindings.title[layer]
  w:down(HOLD[layer])
  if starter then w:press(starter) end
  w:press(key, shift and { shift = true } or nil)
  w:advance(2)
  local note = w.overlay.visible and w.overlay.title ~= title and w.overlay.title or nil
  w:up(HOLD[layer])
  w:settle()
  local parts = w:effects()
  if note then parts[#parts + 1] = ("overlay %q"):format(note) end
  for _, p in ipairs(w.problems) do problems[#problems + 1] = p end
  for _, warning in ipairs(w:takeWarnings()) do problems[#problems + 1] = "warning: " .. warning end
  return parts
end

local function section(lines, header, layer, front, starter, shifts, problems)
  lines[#lines + 1] = ""
  lines[#lines + 1] = "# " .. header
  local any = false
  for _, key in ipairs(KEYS) do
    for _, shift in ipairs(shifts) do
      local parts = probe(layer, front, starter, key, shift, problems)
      if #parts > 0 then
        any = true
        lines[#lines + 1] = ("%-14s %s"):format((shift and "shift+" or "") .. key, table.concat(parts, " ; "))
      end
    end
  end
  if not any then lines[#lines + 1] = "(nothing)" end
end

local function chordStarters(bindings, layer)
  local starters = {}
  for _, column in ipairs(bindings.layer) do
    for _, row in ipairs(column) do
      if row.chord and not row.shift and (row.layer == nil or row.layer == layer) then
        local keys = type(row.keys) == "string" and { row.keys } or row.keys
        for _, key in ipairs(keys) do
          starters[#starters + 1] = { key = key, title = bindings.chords[row.chord].title }
        end
      end
    end
  end
  table.sort(starters, function(a, b) return a.key < b.key end)
  return starters
end

local function generate()
  local w = world.new()
  local bindings = w.modules.bindings
  local apps = {}
  for bundle in pairs(w.modules.targets.apps) do apps[#apps + 1] = bundle end
  table.sort(apps)
  apps[#apps + 1] = UNLISTED

  local lines = {
    "# Generated by keybindings/test/run.lua --update. Each line is a key and what",
    "# it did: posted keys, processes started, menu items tried, and the overlay",
    "# left showing. Keys that did nothing are left out.",
  }
  local problems = {}
  local BOTH, PLAIN = { false, true }, { false }

  section(lines, "System layer, Caps Lock held", "os", UNLISTED, nil, BOTH, problems)
  for _, s in ipairs(chordStarters(bindings, "os")) do
    section(lines, ("System layer, %s then the key (%s)"):format(s.key, s.title), "os", UNLISTED, s.key, PLAIN, problems)
  end
  for _, app in ipairs(apps) do
    section(lines, "App layer, Fn held, in " .. app, "app", app, nil, BOTH, problems)
    for _, s in ipairs(chordStarters(bindings, "app")) do
      section(lines, ("App layer, %s then the key (%s), in %s"):format(s.key, s.title, app), "app", app, s.key, PLAIN, problems)
    end
  end
  return table.concat(lines, "\n") .. "\n", problems
end

return { generate = generate }
